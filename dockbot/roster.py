def matches(plate: str, name: str, roster_name: str, roster_plate: str) -> bool:
    return plate == roster_plate and _fold(name) == _fold(roster_name)


def _fold(value: str) -> str:
    folded = value.replace("ё", "е").replace("Ё", "Е")
    return " ".join(folded.casefold().split())
